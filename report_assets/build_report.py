def set_run_font(run, size=None, bold=None, east=FONT_CN, latin=FONT_EN, color=None):
    run.font.name = latin
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:eastAsia"), east)
    rfonts.set(qn("w:ascii"), latin)
    rfonts.set(qn("w:hAnsi"), latin)
    if size:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)


def shade(cell_or_p, hexcolor):
    el = cell_or_p._element
    pr = el.get_or_add_tcPr() if hasattr(el, "get_or_add_tcPr") else el.get_or_add_pPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hexcolor)
    pr.append(shd)


class Report:
    def __init__(self, doc):
        self.doc = doc
        self.headings = []  # (level, text)

    # ---------------------------------------------------------------- 标题
    def h1(self, text, page_break=True):
        p = self.doc.add_paragraph(style="Heading 1")
        p.paragraph_format.first_line_indent = Pt(0)
        if page_break:
            p.paragraph_format.page_break_before = True
        r = p.add_run(text)
        set_run_font(r, 16, True, east=FONT_HEAD, latin=FONT_EN)
        self.headings.append((1, text))
        return p

    def h2(self, text):
        p = self.doc.add_paragraph(style="Heading 2")
        p.paragraph_format.first_line_indent = Pt(0)
        r = p.add_run(text)
        set_run_font(r, 15, True, east=FONT_HEAD, latin=FONT_EN)
        self.headings.append((2, text))
        return p

    def h3(self, text):
        p = self.doc.add_paragraph(style="Heading 3")
        p.paragraph_format.first_line_indent = Pt(0)
        r = p.add_run(text)
        set_run_font(r, 14, True, east=FONT_HEAD, latin=FONT_EN)
        self.headings.append((3, text))
        return p

    def h4(self, text):
        p = self.doc.add_paragraph(style="Heading 4")
        p.paragraph_format.first_line_indent = Pt(0)
        r = p.add_run(text)
        set_run_font(r, 12, True, east=FONT_HEAD, latin=FONT_EN)
        self.headings.append((4, text))
        return p

    # ---------------------------------------------------------------- 正文
    def p(self, text, indent=True, size=12, bold=False, align=None, space_after=0,
          line=1.25):
        p = self.doc.add_paragraph()
        pf = p.paragraph_format
        pf.first_line_indent = Pt(size * 2) if indent else Pt(0)
        pf.line_spacing = line
        pf.space_before = Pt(0)
        pf.space_after = Pt(space_after)
        if align is not None:
            p.alignment = align
        # 支持 {{n}} 上标引注
        parts = re.split(r"(\{\{\d+\}\})", text)
        for part in parts:
            if not part:
                continue
            m = re.fullmatch(r"\{\{(\d+)\}\}", part)
            if m:
                r = p.add_run(f"[{m.group(1)}]")
                set_run_font(r, size - 2, bold)
                r.font.superscript = True
            else:
                r = p.add_run(part)
                set_run_font(r, size, bold)
        return p

    def bullet(self, items, size=12):
        for it in items:
            p = self.p(it, indent=True, size=size)
            p.paragraph_format.left_indent = Pt(0)

    def figure(self, filename, caption, width=14.8):
        path = filename if os.path.isabs(filename) else os.path.join(FIG, filename)
        p = self.doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Pt(0)
        p.paragraph_format.space_before = Pt(8)
        p.paragraph_format.space_after = Pt(4)
        p.paragraph_format.line_spacing = 1.0
        run = p.add_run()
        run.add_picture(path, width=Cm(width))
        self.caption(caption)

    def caption(self, text):
        p = self.doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Pt(0)
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(8)
        p.paragraph_format.line_spacing = 1.0
        r = p.add_run(text)
        set_run_font(r, 10.5, False, east=FONT_HEAD, latin=FONT_EN)

    # ---------------------------------------------------------------- 表格
    def table(self, caption, headers, rows, widths=None, font_size=9, header_fill="D9E2F3"):
        self.caption(caption)
        t = self.doc.add_table(rows=1 + len(rows), cols=len(headers))
        t.style = "Table Grid"
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        t.autofit = False
        # 表头
        for j, h in enumerate(headers):
            cell = t.rows[0].cells[j]
            cell.text = ""
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.first_line_indent = Pt(0)
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(2)
            r = p.add_run(h)
            set_run_font(r, font_size, True)
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            shade(cell, header_fill)
        # 表头重复
        trPr = t.rows[0]._tr.get_or_add_trPr()
        th = OxmlElement("w:tblHeader")
        th.set(qn("w:val"), "true")
        trPr.append(th)
        # 数据
        for i, row in enumerate(rows, start=1):
            for j, val in enumerate(row):
                cell = t.rows[i].cells[j]
                cell.text = ""
                p = cell.paragraphs[0]
                p.paragraph_format.first_line_indent = Pt(0)
                p.paragraph_format.space_before = Pt(1)
                p.paragraph_format.space_after = Pt(1)
                p.paragraph_format.line_spacing = 1.0
                p.alignment = WD_ALIGN_PARAGRAPH.LEFT
                r = p.add_run(str(val))
                set_run_font(r, font_size, False)
                cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        if widths:
            for j, w in enumerate(widths):
                for row in t.rows:
                    row.cells[j].width = Cm(w)
        # 表后空行
        sp = self.doc.add_paragraph()
        sp.paragraph_format.space_after = Pt(2)
        sp.paragraph_format.line_spacing = 1.0
        return t

    def usecase(self, caption, no, name, actor, priority, desc, inp, out, pre, flow, alt, exc):
        rows = []
        t = self.doc.add_table(rows=2, cols=4)
        t.style = "Table Grid"
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        head = [("用例编号", no, "用例名称", name), ("活动者（Actor）", actor, "优先级", priority)]
        for i, row in enumerate(head):
            for j, val in enumerate(row):
                cell = t.rows[i].cells[j]
                cell.text = ""
                p = cell.paragraphs[0]
                p.paragraph_format.first_line_indent = Pt(0)
                p.paragraph_format.space_before = Pt(1)
                p.paragraph_format.space_after = Pt(1)
                r = p.add_run(val)
                set_run_font(r, 9, j % 2 == 0)
                if j % 2 == 0:
                    shade(cell, "EDF2F9")
        data = [("描述", desc), ("输入", inp), ("输出", out), ("前置条件", pre),
                ("基本流程", flow), ("可选流程", alt), ("异常流程", exc)]
        for label, val in data:
            row = t.add_row()
            c0 = row.cells[0]
            c0.text = ""
            p = c0.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.first_line_indent = Pt(0)
            r = p.add_run(label)
            set_run_font(r, 9, True)
            shade(c0, "EDF2F9")
            merged = row.cells[1].merge(row.cells[3])
            merged.text = ""
            p = merged.paragraphs[0]
            p.paragraph_format.first_line_indent = Pt(0)
            p.paragraph_format.space_before = Pt(1)
            p.paragraph_format.space_after = Pt(1)
            r = p.add_run(val)
            set_run_font(r, 9, False)
        for j, w in enumerate([3.0, 4.0, 3.2, 4.6]):
            for row in t.rows:
                row.cells[j].width = Cm(w)
        self.caption(caption)

    def schema(self, text):
        """关系模式：_主键_ 下划线，*外键* 斜体"""
        p = self.doc.add_paragraph()
        pf = p.paragraph_format
        pf.first_line_indent = Pt(24)
        pf.line_spacing = 1.25
        pf.space_after = Pt(0)
        tokens = re.split(r"(_[^_]+_|\*[^*]+\*)", text)
        for tok in tokens:
            if not tok:
                continue
            if tok.startswith("_") and tok.endswith("_") and len(tok) > 2:
                r = p.add_run(tok[1:-1])
                set_run_font(r, 12)
                r.font.underline = True
            elif tok.startswith("*") and tok.endswith("*") and len(tok) > 2:
                r = p.add_run(tok[1:-1])
                set_run_font(r, 12)
                r.font.italic = True
            else:
                r = p.add_run(tok)
                set_run_font(r, 12)

    def code(self, text, size=9):
        for line in text.split("\n"):
            p = self.doc.add_paragraph()
            pf = p.paragraph_format
            pf.first_line_indent = Pt(0)
            pf.left_indent = Cm(0.5)
            pf.line_spacing = 1.0
            pf.space_before = Pt(0)
            pf.space_after = Pt(0)
            r = p.add_run(line if line else " ")
            set_run_font(r, size, False, east=FONT_CN, latin="Consolas")
            shade(p, "F2F2F2")

    def ref(self, text):
        p = self.doc.add_paragraph()
        pf = p.paragraph_format
        pf.first_line_indent = Cm(-0.74)
        pf.left_indent = Cm(0.74)
        pf.line_spacing = 1.25
        pf.space_after = Pt(2)
        r = p.add_run(text)
        set_run_font(r, 10.5)


