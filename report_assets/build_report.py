def main():
    doc = Document(TEMPLATE)
    body = doc.element.body

    # ---- 封面信息
    p9 = doc.paragraphs[9]
    for r in p9.runs:
        r.text = ""
    p9.runs[0].text = "项目名称："
    r = p9.add_run("VANPINE SRM 全球供应商管理系统的设计与实现")
    set_run_font(r, 18)
    p12 = doc.paragraphs[12]
    for r in p12.runs:
        r.text = ""
    r = p12.add_run("第 X 组项目组成员与分工、成绩评定")
    set_run_font(r, 16, True)
    p15 = doc.paragraphs[15]
    for r in p15.runs:
        r.text = ""
    r = p15.add_run("2026 年 11 月 6 日")
    set_run_font(r, 18)

    # ---- 定位 TOC 分节符与第1章
    first_ch = None
    first_ch_idx = None
    for i, p in enumerate(doc.paragraphs):
        if p.style.name == "Heading 1" and p.text.strip().startswith("第1章"):
            first_ch = p._p
            first_ch_idx = i
            break
    toc_anchor = None
    for p in reversed(doc.paragraphs[:first_ch_idx]):
        ppr = p._p.find(qn("w:pPr"))
        if ppr is not None and ppr.find(qn("w:sectPr")) is not None:
            toc_anchor = p._p
            break
    if first_ch is None:
        raise RuntimeError("未找到第1章标题")
    if toc_anchor is None:
        # 退化为第1章前一个段落
        toc_anchor = first_ch.getprevious()

    # ---- 删除目录中的旧条目（保留“目 录”标题与分节符）
    children = list(body.iterchildren())
    start = children.index(toc_anchor)
    # 找到目录标题
    toc_title_idx = None
    for i, ch in enumerate(children):
        if ch.tag == qn("w:p"):
            from docx.text.paragraph import Paragraph
            if Paragraph(ch, doc).text.strip() == "目  录":
                toc_title_idx = i
                break
    for ch in children[toc_title_idx + 1:start]:
        body.remove(ch)

    # ---- 删除第1章及之后的正文内容（保留末尾 sectPr）
    children = list(body.iterchildren())
    idx = children.index(first_ch)
    for ch in children[idx:]:
        if ch.tag == qn("w:sectPr"):
            continue
        body.remove(ch)

    # ---- 写入正文
    r = Report(doc)
    build_body(r)

    # ---- 插入目录条目
    page_map = {}
    if os.path.exists(PAGE_MAP):
        page_map = json.load(open(PAGE_MAP, encoding="utf8"))
    toc_paras = []
    for level, text in r.headings:
        if level > 3:
            continue
        p = doc.add_paragraph(style=f"toc {level}")
        pf = p.paragraph_format
        pf.first_line_indent = Pt(0)
        pf.tab_stops.add_tab_stop(Cm(15.2), WD_TAB_ALIGNMENT.RIGHT, WD_TAB_LEADER.DOTS)
        page = page_map.get(text, "")
        run = p.add_run(text + "\t" + str(page))
        set_run_font(run, 12 if level == 1 else 10.5, level == 1)
        toc_paras.append(p)

    # 将目录段落移动到分节符之前（保持顺序）
    for p in toc_paras:
        toc_anchor.addprevious(p._p)

    # ---- 更新字段设置
    settings = doc.settings.element
    update = settings.find(qn("w:updateFields"))
    if update is None:
        update = OxmlElement("w:updateFields")
        settings.append(update)
    update.set(qn("w:val"), "true")

    # ---- 文档属性
    doc.core_properties.title = "VANPINE SRM 全球供应商管理系统的设计与实现"
    doc.core_properties.subject = "企业项目实践报告"
    doc.core_properties.author = "Vanpine"

    doc.save(OUTPUT)
    print("saved:", OUTPUT)
    print("headings:", len(r.headings))


if __name__ == "__main__":
    main()
